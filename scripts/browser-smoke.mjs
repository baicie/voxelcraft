import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-unsafe-swiftshader', '--disable-dev-shm-usage'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', error => { errors.push(error.stack || error.message); console.log('PAGEERROR', error.message); });
page.on('console', message => { if (message.type() === 'error') console.log('CONSOLE', message.text()); });
await page.goto('http://127.0.0.1:4179/', { waitUntil: 'domcontentloaded', timeout: 60000 });
await mkdir('docs/benchmarks/k3.1-pro/screenshots', { recursive: true });
await page.screenshot({ path: 'docs/benchmarks/k3.1-pro/screenshots/tmp-menu.png' });
console.log('title', await page.title());
console.log('main menu visible', await page.locator('[data-testid="main-menu"]').isVisible());
await page.locator('[data-testid="new-world"]').click();
await page.locator('[data-testid="world-name"]').fill('Browser Smoke');
await page.locator('[data-testid="world-seed"]').fill('482193');
await page.locator('[data-testid="create-world"]').click();
await page.waitForSelector('#game-world', { state: 'visible', timeout: 30000 });
await page.waitForSelector('#start-hint', { state: 'visible', timeout: 60000 });
await page.screenshot({ path: 'docs/benchmarks/k3.1-pro/screenshots/tmp-game.png' });
console.log('hud visible', await page.locator('[data-testid="hud"]').isVisible());
console.log('stats', await page.evaluate(() => window.__VOXELCRAFT__?.stats()));
await page.locator('#game-world').click({ position: { x: 720, y: 450 } });
await page.waitForTimeout(800);
console.log('pointerLock', await page.evaluate(() => !!document.pointerLockElement));
await page.keyboard.down('w');
await page.waitForTimeout(1000);
await page.keyboard.up('w');
console.log('position', await page.evaluate(() => window.__VOXELCRAFT__?.position()));
await page.screenshot({ path: 'docs/benchmarks/k3.1-pro/screenshots/tmp-after-move.png' });
console.log('errors', errors.length ? errors : 'none');
await browser.close();

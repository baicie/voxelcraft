import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-unsafe-swiftshader', '--disable-dev-shm-usage'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', error => { errors.push(error.message); console.log('PAGEERROR', error.message); });
page.on('console', message => { if (message.type() === 'error') console.log('CONSOLE', message.text()); });
const dir = 'docs/benchmarks/k3.1-pro/screenshots';
await mkdir(dir, { recursive: true });
await page.goto('http://127.0.0.1:4180/', { waitUntil: 'domcontentloaded', timeout: 60000 });
await page.evaluate(() => new Promise(resolve => { const request = indexedDB.deleteDatabase('voxelcraft-k3'); request.onsuccess = request.onerror = request.onblocked = () => resolve(); }));
await page.reload({ waitUntil: 'domcontentloaded' });
await page.locator('[data-testid="new-world"]').click();
await page.locator('[data-testid="world-name"]').fill('Alder Hollow');
await page.locator('[data-testid="world-seed"]').fill('482193');
await page.locator('[data-testid="create-world"]').click();
await page.waitForSelector('#start-hint', { state: 'visible', timeout: 60000 });
await page.screenshot({ path: `${dir}/01-spawn.png` });
console.log('spawn', await page.evaluate(() => window.__VOXELCRAFT__.position()));
await page.locator('#game-world').click({ position: { x: 720, y: 450 } });
await page.waitForTimeout(600);
console.log('locked', await page.evaluate(() => !!document.pointerLockElement));
const before = await page.evaluate(() => window.__VOXELCRAFT__.inventory());
await page.mouse.down({ button: 'left' });
await page.waitForTimeout(2800);
await page.mouse.up({ button: 'left' });
await page.keyboard.down('w');
await page.waitForTimeout(900);
await page.keyboard.up('w');
await page.waitForTimeout(1400);
const after = await page.evaluate(() => window.__VOXELCRAFT__.inventory());
console.log('mined inventory', after.filter(Boolean), 'before nonempty', before.filter(Boolean));
await page.screenshot({ path: `${dir}/02-mined.png` });
await page.keyboard.press('e');
await page.waitForSelector('[data-testid="inventory-screen"]', { state: 'visible', timeout: 10000 });
await page.screenshot({ path: `${dir}/03-inventory.png` });
const logSlot = page.locator('#inventory-hotbar .item-slot:has(img[alt*="Oak"])').first();
console.log('log slots', await page.locator('#inventory-hotbar .item-slot:has(img[alt*="Oak"])').count());
if (await logSlot.count()) {
  await logSlot.click();
  await page.locator('#craft-grid .item-slot').first().click();
  await page.waitForTimeout(250);
  await page.locator('#craft-result').click();
  await page.waitForTimeout(250);
  console.log('main empty count', await page.locator('#inventory-main .item-slot[data-empty="true"]').count());
  const empty = page.locator('#inventory-main .item-slot[data-empty="true"]').first();
  await empty.click();
}
const crafted = await page.evaluate(() => window.__VOXELCRAFT__.inventory());
console.log('crafted inventory', crafted.filter(Boolean));
await page.screenshot({ path: `${dir}/04-crafted.png` });
await page.locator('#close-inventory').click();
await page.waitForTimeout(400);
await page.keyboard.press('Escape');
await page.evaluate(() => { if (document.pointerLockElement) document.exitPointerLock(); });
await page.waitForSelector('[data-testid="pause-menu"]', { state: 'visible', timeout: 10000 });
await page.screenshot({ path: `${dir}/05-pause.png` });
await page.locator('[data-testid="save-exit"]').click();
await page.waitForSelector('[data-testid="main-menu"]:visible', { state: 'visible', timeout: 15000 });
await page.screenshot({ path: `${dir}/06-saved-menu.png` });
console.log('worlds', await page.locator('.world-card').count());
await page.locator('[data-testid="play-world"]').first().click();
await page.waitForSelector('#start-hint', { state: 'visible', timeout: 60000 });
await page.waitForTimeout(500);
const restored = await page.evaluate(() => window.__VOXELCRAFT__.inventory());
console.log('restored inventory', restored.filter(Boolean));
await page.screenshot({ path: `${dir}/07-reloaded.png` });
console.log('errors', errors);
await browser.close();
